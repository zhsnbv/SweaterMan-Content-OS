export function systemPrompt(scope: Scope, contextBlock: string, actor: string): string {
  return [
    SHARED,
    SCOPE_INSTRUCTIONS[scope.kind],
    `Текущий пользователь: ${actor}. Сегодня: ${new Date().toISOString().slice(0, 10)}.`,
    '--- НАЧАЛО СОБРАННОГО КОНТЕКСТА ---',
    contextBlock,
    '--- КОНЕЦ СОБРАННОГО КОНТЕКСТА ---',
  ].join('\n\n');
}

